public class typecasting {
    public static void main(String[] args){
        char ch='A';
        int x=ch;//implicit typecasting
        System.out.println(x);

        char piyush='$';
        int y=(int)piyush;//explicit typecasting
        System.out.println(y);

        char harsh = '3';
        System.out.println((int)harsh);
    }

}
